class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute total page count."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(54, 750, "DigitalShield Forensic Analysis Report")
            self.drawRightString(558, 750, f"Confidential Forensic Record")
            self.setStrokeColor(colors.HexColor("#e2e8f0"))
            self.setLineWidth(0.5)
            self.line(54, 745, 558, 745)

        # Footer
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(54, 45, 558, 45)
        self.drawString(54, 32, f"Generated by DigitalShield Forensic Suite | Strictly Confidential")
        self.drawRightString(558, 32, f"Page {self._pageNumber} of {page_count}")
        self.restoreState()


class PDFRenderer:
    """Renders ReportData into a PDF file using ReportLab."""

    @staticmethod
    def render(report: ReportData, output_path: Union[str, Path, io.BytesIO]) -> None:
        doc = SimpleDocTemplate(
            output_path if isinstance(output_path, (str, io.BytesIO)) else str(output_path),
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        styles = getSampleStyleSheet()
        
        # Custom styles
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=18,
            leading=22,
            textColor=colors.HexColor("#1e293b"),
            spaceAfter=4,
        )
        h2_style = ParagraphStyle(
            "SectionH2",
            parent=styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=12,
            leading=16,
            textColor=colors.HexColor("#0f172a"),
            spaceBefore=12,
            spaceAfter=6,
        )
        h3_style = ParagraphStyle(
            "SectionH3",
            parent=styles["Heading3"],
            fontName="Helvetica-Bold",
            fontSize=10,
            leading=13,
            textColor=colors.HexColor("#334155"),
            spaceBefore=8,
            spaceAfter=4,
        )
        body_style = ParagraphStyle(
            "Body",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=11.5,
            textColor=colors.HexColor("#0f172a"),
        )
        body_bold = ParagraphStyle(
            "BodyBold",
            parent=body_style,
            fontName="Helvetica-Bold",
        )
        meta_label = ParagraphStyle(
            "MetaLabel",
            parent=body_style,
            fontName="Helvetica-Bold",
            textColor=colors.HexColor("#334155"),
        )
        code_style = ParagraphStyle(
            "CodeStyle",
            parent=body_style,
            fontName="Courier",
            fontSize=7.5,
            leading=9.5,
            textColor=colors.HexColor("#0f172a"),
        )
        warning_style = ParagraphStyle(
            "WarningText",
            parent=body_style,
            fontName="Helvetica",
            fontSize=8,
            leading=11,
            textColor=colors.HexColor("#92400e"),
        )
        callout_style = ParagraphStyle(
            "CalloutText",
            parent=body_style,
            fontName="Helvetica-Oblique",
            fontSize=8,
            leading=10.5,
            textColor=colors.HexColor("#475569"),
        )

        story = []
        meta = report.metadata
        case = report.case_info

        # --- Document Header ---
        story.append(Paragraph("DigitalShield Forensic Analysis Report", title_style))
        story.append(Paragraph(f"Case: <b>{case.name}</b> (ID: {case.case_id})", body_style))
        story.append(Spacer(1, 4))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0284c7"), spaceAfter=10))

        # Metadata Header Table
        header_data = [
            [Paragraph("Report ID:", meta_label), Paragraph(meta.report_id, code_style),
             Paragraph("Report Date:", meta_label), Paragraph(meta.report_timestamp, body_style)],
            [Paragraph("Case ID:", meta_label), Paragraph(case.case_id, code_style),
             Paragraph("Investigator:", meta_label), Paragraph(meta.investigator or "Unassigned", body_style)],
            [Paragraph("Case Status:", meta_label), Paragraph(case.status, body_style),
             Paragraph("Software:", meta_label), Paragraph(f"{meta.tool_name} v{meta.software_version}", body_style)],
        ]
        t_hdr = Table(header_data, colWidths=[70, 180, 80, 174])
        t_hdr.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]))
        story.append(t_hdr)
        story.append(Spacer(1, 10))

        # --- Section 1: Case Overview ---
        story.append(Paragraph("1. Case Overview & Scope", h2_style))
        desc_text = case.description if case.description else "None recorded."
        case_data = [
            [Paragraph("Case Initialized:", meta_label), Paragraph(case.created_at, body_style)],
            [Paragraph("Report Generated:", meta_label), Paragraph(meta.report_timestamp, body_style)],
            [Paragraph("Evidence Ingested:", meta_label), Paragraph(f"{len(report.evidence_items)} item(s)", body_style)],
            [Paragraph("Scope Description:", meta_label), Paragraph(desc_text, body_style)],
        ]
        t_case = Table(case_data, colWidths=[110, 394])
        t_case.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#ffffff")),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]))
        story.append(t_case)
        story.append(Spacer(1, 8))

        # --- Reported Public Source URL ---
        story.append(Paragraph("Reported Public Source URL", h2_style))
        if report.reported_source_url:
            source_rows = [
                [Paragraph("Reported Source URL:", meta_label), Paragraph(report.reported_source_url, code_style)],
                [Paragraph("Source Information:", meta_label), Paragraph("URL supplied by the investigator.", body_style)],
                [Paragraph("Verification Status:", meta_label), Paragraph(report.reported_source_url_status or "Not independently verified.", body_style)],
                [Paragraph("Recorded (UTC):", meta_label), Paragraph(report.reported_source_url_recorded_at or "Not recorded", body_style)],
                [Paragraph("Associated Case ID:", meta_label), Paragraph(meta.case_id, code_style)],
            ]
            if report.reported_source_url_evidence_id:
                source_rows.append([Paragraph("Associated Evidence ID:", meta_label), Paragraph(report.reported_source_url_evidence_id, code_style)])
            t_source = Table(source_rows, colWidths=[120, 384])
            t_source.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#ffffff")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]))
            story.append(t_source)
            story.append(Spacer(1, 3))
            story.append(Paragraph("Note: URL supplied by investigator as reported observation location. Not proof of authorship or ownership.", callout_style))
        else:
            story.append(Paragraph("No public source URL was provided by the investigator.", body_style))
        story.append(Spacer(1, 8))

        # --- Section 2: Evidence Inventory ---
        story.append(Paragraph("2. Evidence Inventory & Cryptographic Baseline", h2_style))
        story.append(Paragraph("SHA-256 digests represent the preserved, read-only baseline copies in local vaults.", callout_style))
        story.append(Spacer(1, 4))
        
        if not report.evidence_items:
            story.append(Paragraph("No evidence items registered in this case.", body_style))
        else:
            ev_table_data = [[
                Paragraph("Evidence ID", body_bold),
                Paragraph("Filename", body_bold),
                Paragraph("MIME / Size", body_bold),
                Paragraph("Ingested (UTC)", body_bold),
                Paragraph("SHA-256 Digest", body_bold),
            ]]
            for ev in report.evidence_items:
                ev_table_data.append([
                    Paragraph(ev.evidence_id, code_style),
                    Paragraph(ev.original_filename, body_style),
                    Paragraph(f"{ev.mime_type}<br/>{ev.file_size:,} B", body_style),
                    Paragraph(ev.import_timestamp[:19].replace("T", " "), body_style),
                    Paragraph(ev.sha256[:28] + "...", code_style),
                ])
            t_ev = Table(ev_table_data, colWidths=[80, 110, 80, 95, 139])
            t_ev.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]))
            story.append(t_ev)

        story.append(Spacer(1, 8))

        # --- Section 3: Technical & EXIF Metadata ---
        if report.metadata_findings:
            story.append(Paragraph("3. Technical & EXIF Metadata Findings", h2_style))
            for ev_id, m in report.metadata_findings.items():
                story.append(Paragraph(f"Evidence {ev_id} Metadata", h3_style))
                if not m:
                    story.append(Paragraph("Metadata extraction was not performed or not available for this item.", body_style))
                    continue
                meta_rows = [
                    [Paragraph("Dimensions / Format:", meta_label), Paragraph(f"{m.get('width_px')}x{m.get('height_px')} px ({m.get('file_format')}, {m.get('color_mode')})", body_style)],
                    [Paragraph("Camera / Device:", meta_label), Paragraph(f"{m.get('camera_make') or 'Not recorded'} {m.get('camera_model') or ''}", body_style)],
                    [Paragraph("Software / Dates:", meta_label), Paragraph(f"{m.get('software') or 'Not recorded'} | Capture: {m.get('datetime_original') or 'Not recorded'}", body_style)],
                    [Paragraph("Camera Settings:", meta_label), Paragraph(f"Exp: {m.get('exposure_time') or 'N/A'}, F/{m.get('f_number') or 'N/A'}, ISO {m.get('iso_speed') or 'N/A'}", body_style)],
                ]
                t_m = Table(meta_rows, colWidths=[120, 384])
                t_m.setStyle(TableStyle([
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                ]))
                story.append(t_m)
                story.append(Paragraph("Note: Absence of EXIF metadata is standard across messaging apps and does not prove manipulation.", callout_style))
                story.append(Spacer(1, 4))

        # --- Section 4: Perceptual Hashes ---
        if report.fingerprint_findings:
            story.append(Paragraph("4. Perceptual Hashing & Similarity Findings", h2_style))
            fp_rows = [[Paragraph("Evidence ID", body_bold), Paragraph("aHash", body_bold), Paragraph("dHash", body_bold), Paragraph("pHash", body_bold)]]
            for ev_id, fp in report.fingerprint_findings.items():
                if fp:
                    fp_rows.append([
                        Paragraph(ev_id, code_style),
                        Paragraph(fp.get("ahash", ""), code_style),
                        Paragraph(fp.get("dhash", ""), code_style),
                        Paragraph(fp.get("phash", ""), code_style),
                    ])
            t_fp = Table(fp_rows, colWidths=[80, 140, 140, 144])
            t_fp.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]))
            story.append(t_fp)
            story.append(Paragraph("Perceptual similarity is an investigative indicator and does not prove identical origin, authorship, or ownership.", callout_style))
            story.append(Spacer(1, 6))

        # --- Section 5: ELA Analysis ---
        if report.ela_findings:
            story.append(Paragraph("5. Error Level Analysis (ELA) Findings", h2_style))
            for ev_id, ela in report.ela_findings.items():
                if not ela:
                    continue
                story.append(Paragraph(f"Evidence {ev_id} Error Level Analysis", h3_style))
                ela_rows = [
                    [Paragraph("Mean / Max Error:", meta_label), Paragraph(f"{ela.get('mean_error', 0.0):.4f} / {ela.get('max_error', 0.0):.4f}", body_style)],
                    [Paragraph("Anomaly Score:", meta_label), Paragraph(f"<b>{ela.get('anomaly_score', 0.0):.4f}</b> (Confidence: {ela.get('confidence', 0.0)*100:.0f}%)", body_style)],
                    [Paragraph("Assessment:", meta_label), Paragraph(ela.get("assessment", ""), body_style)],
                ]
                t_ela = Table(ela_rows, colWidths=[120, 384])
                t_ela.setStyle(TableStyle([
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                ]))
                story.append(t_ela)
                story.append(Paragraph(f"Limitation: {ela.get('disclaimer', '')}", callout_style))
                story.append(Spacer(1, 4))

        # --- Section 6: Deepfake Assessment ---
        if report.deepfake_findings:
            story.append(Paragraph("6. AI-Assisted Assessment — Synthetic Media", h2_style))
            story.append(Paragraph("Warning: AI-assisted findings are probabilistic indicators and do not prove manipulation, identity, authorship, ownership, or criminal culpability.", warning_style))
            story.append(Spacer(1, 4))
            for ev_id, df in report.deepfake_findings.items():
                if not df:
                    continue
                story.append(Paragraph(f"Evidence {ev_id} Assessment", h3_style))
                prob = df.get("synthetic_probability", 0.0)
                conf = df.get("confidence", 0.0)
                df_rows = [
                    [Paragraph("Detector / Type:", meta_label), Paragraph(f"{df.get('detector_name')} ({df.get('detector_type')})", body_style)],
                    [Paragraph("Synthetic Probability:", meta_label), Paragraph(f"<b>{prob:.2f}</b> (0.00 to 1.00)", body_style)],
                    [Paragraph("Confidence:", meta_label), Paragraph(f"{conf*100:.1f}%", body_style)],
                    [Paragraph("Assessment:", meta_label), Paragraph(df.get("assessment", ""), body_style)],
                ]
                t_df = Table(df_rows, colWidths=[120, 384])
                t_df.setStyle(TableStyle([
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                ]))
                story.append(t_df)
                story.append(Spacer(1, 4))

        # --- Section 7: Public URL Provenance ---
        if report.provenance_records:
            story.append(Paragraph("7. Public URL Provenance & Leads", h2_style))
            for rec in report.provenance_records:
                sim = f"{rec.get('similarity_score', 0.0)*100:.1f}%" if rec.get("similarity_score") is not None else "N/A"
                prv_rows = [
                    [Paragraph("Provenance ID:", meta_label), Paragraph(rec.get("provenance_id", ""), code_style)],
                    [Paragraph("Source URL:", meta_label), Paragraph(rec.get("source_url", ""), code_style)],
                    [Paragraph("Observed Account:", meta_label), Paragraph(rec.get("observed_account_name") or "Unknown / Not available", body_style)],
                    [Paragraph("Similarity / Match:", meta_label), Paragraph(f"{sim} ({rec.get('matching_method') or 'None'})", body_style)],
                    [Paragraph("Discovery Time:", meta_label), Paragraph(rec.get("discovery_timestamp", ""), body_style)],
                    [Paragraph("Assessment:", meta_label), Paragraph(rec.get("assessment", ""), body_style)],
                ]
                t_prv = Table(prv_rows, colWidths=[120, 384])
                t_prv.setStyle(TableStyle([
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                ]))
                story.append(t_prv)
                story.append(Spacer(1, 4))

        # --- Section 8: Timeline ---
        if report.timelines:
            story.append(Paragraph("8. Origin & Propagation Timeline", h2_style))
            for ev_id, tl in report.timelines.items():
                events = tl.get("timeline", [])
                if not events:
                    continue
                tl_rows = [[Paragraph("Event", body_bold), Paragraph("Timestamp (UTC)", body_bold), Paragraph("Details", body_bold)]]
                for ev in events:
                    tl_rows.append([
                        Paragraph(ev.get("event_type", ""), code_style),
                        Paragraph(str(ev.get("timestamp", "")), body_style),
                        Paragraph(ev.get("description", ""), body_style),
                    ])
                t_tl = Table(tl_rows, colWidths=[120, 110, 274])
                t_tl.setStyle(TableStyle([
                    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                    ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                    ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
                ]))
                story.append(t_tl)
                story.append(Spacer(1, 4))

        # --- Section 9: Audit Trail ---
        if report.audit_events:
            story.append(Paragraph("9. Audit Trail & Chain of Custody Summary", h2_style))
            aud_rows = [[Paragraph("Timestamp", body_bold), Paragraph("Action", body_bold), Paragraph("Actor", body_bold), Paragraph("Hash (SHA-256)", body_bold)]]
            for a in report.audit_events[-15:]:
                h_str = a.get("entry_hash", "")[:16] + "..." if a.get("entry_hash") else "N/A"
                aud_rows.append([
                    Paragraph(a.get("timestamp", "")[:19].replace("T", " "), body_style),
                    Paragraph(a.get("action", ""), code_style),
                    Paragraph(a.get("actor", ""), body_style),
                    Paragraph(h_str, code_style),
                ])
            t_aud = Table(aud_rows, colWidths=[100, 160, 90, 154])
            t_aud.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 2.5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5),
            ]))
            story.append(t_aud)
            story.append(Spacer(1, 6))

        # --- Section 10: Findings & Limitations ---
        story.append(Paragraph("10. Summary of Objective Findings", h2_style))
        for item in (report.overall_findings or ["Evidence preserved and verified against SHA-256 baseline."]):
            story.append(Paragraph(f"• {item}", body_style))
        story.append(Spacer(1, 6))

        story.append(Paragraph("11. Forensic & Legal Limitations", h2_style))
        for lim in (report.limitations or ["Analysis outputs are probabilistic and require independent human review."]):
            story.append(Paragraph(f"• {lim}", body_style))
        story.append(Spacer(1, 6))

        # --- Section 12: Notes ---
        story.append(Paragraph("12. Investigator / Case Notes", h2_style))
        story.append(Paragraph(report.investigator_notes if report.investigator_notes else "None recorded.", body_style))

        # Build PDF with dynamic NumberedCanvas
        doc.build(story, canvasmaker=NumberedCanvas)
